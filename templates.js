window.findTemplate = function (cat) {
  const ch = window.currentChapter || 'jifen';
  const pool = ch === 'weifen' ? window.TEMPLATES_DIFF : window.TEMPLATES;
  let best = null, bestLen = -1;
  for (const t of pool) {
    if (t.match.length <= cat.length &&
        t.match.every((m, i) => m === cat[i]) &&
        t.match.length > bestLen) {
      best = t; bestLen = t.match.length;
    }
  }
  return best;
};

